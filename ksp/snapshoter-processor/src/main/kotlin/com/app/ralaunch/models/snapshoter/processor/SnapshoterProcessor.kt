package com.app.ralaunch.models.snapshoter.processor

import com.google.devtools.ksp.processing.Dependencies
import com.google.devtools.ksp.processing.Resolver
import com.google.devtools.ksp.processing.SymbolProcessor
import com.google.devtools.ksp.processing.SymbolProcessorEnvironment
import com.google.devtools.ksp.processing.SymbolProcessorProvider
import com.google.devtools.ksp.symbol.KSClassDeclaration
import com.google.devtools.ksp.symbol.KSFile
import com.google.devtools.ksp.symbol.KSPropertyDeclaration
import com.google.devtools.ksp.symbol.KSType
import com.google.devtools.ksp.symbol.Modifier
import com.squareup.kotlinpoet.CodeBlock
import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.FunSpec
import com.squareup.kotlinpoet.ksp.toClassName

/**
 * KSP 处理器：扫描标注 `@Snapshoter` 的 data class，用 kotlinpoet 在
 * `com.app.ralaunch.models.snapshoter` 包下生成 `<Model>Snapshoter.kt`，
 * 内含顶层扩展函数 `Model.snapshot(): Model`（import 后以 `model.snapshot()`
 * 调用，也支持非绑定函数引用 `Model::snapshot`），基于 copy() 深拷贝所有属性：
 *
 * - Kotlin 内置集合（List/Collection/Iterable/Set/Map 及 Mutable 变体，含任意嵌套）：
 *   生成全新容器并逐元素/逐键值递归深拷贝；
 * - 属性或集合元素为其他标注 `@Snapshoter` 的 data class 时，
 *   调用其生成的 `<Type>.snapshot()` 扩展递归深拷贝；
 * - 其余引用类型（未标注 @Snapshoter 的 data class、数组、Pair/Triple 等）
 *   与原对象共享引用 —— 限制已在生成函数的 KDoc 中标注。
 */
class SnapshoterProcessor(environment: SymbolProcessorEnvironment) : SymbolProcessor {

    private val codeGenerator = environment.codeGenerator
    private val logger = environment.logger
    private var processed = false
    private val generatedFileNames = mutableSetOf<String>()

    override fun process(resolver: Resolver): List<KSFile> {
        if (processed) return emptyList() // KSP 多轮处理去重
        processed = true

        resolver.getSymbolsWithAnnotation(SNAPSHOTER_FQN)
            .filterIsInstance<KSClassDeclaration>()
            .forEach { declaration ->
                if (validate(declaration)) generate(declaration)
            }
        return emptyList()
    }

    private fun validate(declaration: KSClassDeclaration): Boolean {
        val fqName = declaration.qualifiedName?.asString()
            ?: declaration.simpleName.asString()

        if (Modifier.DATA !in declaration.modifiers) {
            logger.error("@Snapshoter 只能标注在 data class 上: $fqName")
            return false
        }
        if (declaration.primaryConstructor == null) {
            logger.error("$fqName 缺少主构造函数，无法生成 Snapshoter")
            return false
        }
        if (Modifier.PRIVATE in declaration.modifiers) {
            logger.error("$fqName 是 private 的，生成代码无法访问其构造函数")
            return false
        }
        if (!generatedFileNames.add(fileName(declaration))) {
            logger.error("${fileName(declaration)}.kt 与其他同名 data class 的生成文件冲突，无法为 $fqName 生成")
            return false
        }
        return true
    }

    private fun fileName(declaration: KSClassDeclaration): String =
        "${declaration.simpleName.asString()}Snapshoter"

    private fun generate(declaration: KSClassDeclaration) {
        val simpleName = declaration.simpleName.asString()
        val name = fileName(declaration)
        val modelClass = declaration.toClassName()

        // copy() 只能按属性名覆写；跳过非属性的主构造参数（沿用原值）
        val propertyNames = declaration.declarations
            .filterIsInstance<KSPropertyDeclaration>()
            .map { it.simpleName.asString() }
            .toSet()

        // 扩展接收者作用域内直接引用属性名（隐式 this）
        val argBlocks = declaration.primaryConstructor!!.parameters.mapNotNull { param ->
            val paramName = param.name?.asString() ?: return@mapNotNull null
            if (paramName !in propertyNames) return@mapNotNull null
            val copied = copyExpr(param.type.resolve(), paramName)
                ?: return@mapNotNull null // 无需深拷贝：copy() 默认参数即为该值
            CodeBlock.of("%N = %L", paramName, copied)
        }

        val body = CodeBlock.builder().add("return copy(")
        if (argBlocks.isEmpty()) {
            body.add(")")
        } else {
            body.add("\n")
            argBlocks.forEachIndexed { index, block ->
                body.add("    %L", block)
                if (index != argBlocks.lastIndex) body.add(",\n")
            }
            body.add("\n)")
        }

        val snapshotExtension = FunSpec.builder("snapshot")
            .receiver(modelClass)
            .returns(modelClass)
            .addKdoc("%L", snapshotKdoc(simpleName))
            .addCode(body.build())
            .build()

        val fileSpec = FileSpec.builder(GENERATED_PACKAGE, name)
            .addFileComment("Generated by SnapshoterProcessor — do not edit")
            .addFunction(snapshotExtension)
            .build()

        val dependencies = declaration.containingFile
            ?.let { Dependencies(false, it) }
            ?: Dependencies.ALL_FILES
        codeGenerator.createNewFile(dependencies, GENERATED_PACKAGE, name)
            .use { out -> out.writer().use(fileSpec::writeTo) }
        logger.info("✅ Generated snapshot extension: $name")
    }

    /**
     * 返回 [expr]（静态类型 [type]）的深拷贝表达式；无需深拷贝（值类型/不支持的类型）返回 null。
     */
    private fun copyExpr(type: KSType, expr: String): CodeBlock? {
        val declaration = type.declaration
        val fqn = declaration.qualifiedName?.asString()
            ?: return null // 类型参数/未解析类型 → 共享引用
        val nullable = type.isMarkedNullable
        val inner = if (nullable) type.makeNotNullable() else type

        // 集合元素的深拷贝表达式；星号投影（无法得知元素类型）保留原元素引用
        fun elementExpr(argIndex: Int, varName: String): CodeBlock {
            val argType = inner.arguments.getOrNull(argIndex)?.type?.resolve()
                ?: return CodeBlock.of("%L", varName)
            return copyExpr(argType, varName) ?: CodeBlock.of("%L", varName)
        }

        return when (fqn) {
            in LIST_FQNS ->
                if (nullable) CodeBlock.of("$expr?.map { %L }", elementExpr(0, "it"))
                else CodeBlock.of("$expr.map { %L }", elementExpr(0, "it"))

            in SET_FQNS ->
                if (nullable) CodeBlock.of("$expr?.mapTo(LinkedHashSet()) { %L }", elementExpr(0, "it"))
                else CodeBlock.of("$expr.mapTo(LinkedHashSet()) { %L }", elementExpr(0, "it"))

            in MAP_FQNS -> {
                val key = elementExpr(0, "k")
                val value = elementExpr(1, "v")
                if (nullable) CodeBlock.of("$expr?.entries?.associate { (k, v) -> %L to %L }", key, value)
                else CodeBlock.of("$expr.entries.associate { (k, v) -> %L to %L }", key, value)
            }

            else -> {
                // 仅深拷贝同样标注 @Snapshoter 的 data class（含自引用），调用其生成的
                // 同包顶层扩展；其余引用类型共享引用（见生成函数 KDoc 限制说明）
                val classDecl = declaration as? KSClassDeclaration ?: return null
                if (Modifier.DATA !in classDecl.modifiers || !classDecl.isAnnotatedWithSnapshoter()) return null
                if (nullable) CodeBlock.of("$expr?.snapshot()")
                else CodeBlock.of("$expr.snapshot()")
            }
        }
    }

    private fun KSClassDeclaration.isAnnotatedWithSnapshoter(): Boolean =
        annotations.any {
            it.annotationType.resolve().declaration.qualifiedName?.asString() == SNAPSHOTER_FQN
        }

    /** 生成函数 KDoc：标注深拷贝范围与限制（要求见任务说明）。 */
    private fun snapshotKdoc(simpleName: String): String = buildString {
        append("生成 [")
        append(simpleName)
        append("] 的深拷贝快照。\n\n")
        append("深拷贝范围（递归）：\n")
        append("- Kotlin 内置集合（List/Collection/Iterable/Set/Map 及其 Mutable 变体，含任意嵌套组合）：\n")
        append("  生成全新容器，并逐元素/逐键值递归深拷贝；\n")
        append("- 属性或集合元素为其他标注 `@Snapshoter` 的 data class 时（含自引用），\n")
        append("  调用其生成的同包顶层扩展 `<Type>.snapshot()` 递归深拷贝。\n\n")
        append("深拷贝限制（以下属性与原对象共享同一引用，仅浅拷贝）：\n")
        append("- 未标注 `@Snapshoter` 的嵌套 data class 与任意自定义引用类型；\n")
        append("- 数组（Array/IntArray 等）、Pair/Triple 等非内置集合容器；\n")
        append("- 上述类型作为集合元素出现时，仅复制元素引用（容器本身仍是全新实例）。\n\n")
        append("其他限制：\n")
        append("- 存在循环引用的数据结构会导致无限递归（StackOverflowError）。")
    }

    private companion object {
        const val SNAPSHOTER_FQN = "com.app.ralaunch.models.snapshoter.Snapshoter"
        const val GENERATED_PACKAGE = "com.app.ralaunch.models.snapshoter"

        val LIST_FQNS = setOf(
            "kotlin.collections.List",
            "kotlin.collections.MutableList",
            "kotlin.collections.Collection",
            "kotlin.collections.MutableCollection",
            "kotlin.collections.Iterable",
        )
        val SET_FQNS = setOf(
            "kotlin.collections.Set",
            "kotlin.collections.MutableSet",
        )
        val MAP_FQNS = setOf(
            "kotlin.collections.Map",
            "kotlin.collections.MutableMap",
        )
    }
}

class SnapshoterProcessorProvider : SymbolProcessorProvider {
    override fun create(environment: SymbolProcessorEnvironment): SymbolProcessor =
        SnapshoterProcessor(environment)
}
